class TestPointerHelpers:
    def test_read_pointer_missing(self, tmp_path):
        assert read_pointer(tmp_path) == ""

    def test_read_pointer_only_newline(self, tmp_path):
        (tmp_path / RUN_DIR_FILE).write_text("\n")
        assert read_pointer(tmp_path) == ""

    def test_read_pointer_empty_file(self, tmp_path):
        (tmp_path / RUN_DIR_FILE).write_text("")
        assert read_pointer(tmp_path) == ""

    def test_read_pointer_strips_all_newlines(self, tmp_path):
        (tmp_path / RUN_DIR_FILE).write_text("artifacts/a\nartifacts/b\n")
        assert read_pointer(tmp_path) == "artifacts/aartifacts/b"

    def test_read_last_signature_missing(self, tmp_path):
        assert read_last_signature(tmp_path) == ""

    def test_read_last_signature_empty_file(self, tmp_path):
        (tmp_path / RUN_SIG_FILE).write_text("")
        assert read_last_signature(tmp_path) == ""

    def test_read_last_signature_strips_trailing_only(self, tmp_path):
        (tmp_path / RUN_SIG_FILE).write_text("MODE=one_step\n\n")
        assert read_last_signature(tmp_path) == "MODE=one_step"

    def test_read_last_signature_preserves_interior_newlines(self, tmp_path):
        (tmp_path / RUN_SIG_FILE).write_text("a\nb\n")
        assert read_last_signature(tmp_path) == "a\nb"

    def test_write_pointers_run_pointer_has_one_trailing_newline(self, tmp_path):
        write_pointers(
            tmp_path, Path("artifacts/run_one_step_20260805_141530"), "MODE=one_step"
        )
        raw = (tmp_path / RUN_DIR_FILE).read_bytes()
        assert raw.endswith(b"\n")
        assert raw.count(b"\n") == 1

    def test_write_pointers_sig_has_no_trailing_newline(self, tmp_path):
        write_pointers(
            tmp_path, Path("artifacts/run_one_step_20260805_141530"), "MODE=one_step"
        )
        raw = (tmp_path / RUN_SIG_FILE).read_bytes()
        assert not raw.endswith(b"\n")

    def test_write_pointers_round_trips(self, tmp_path):
        run_dir = Path("artifacts/run_one_step_20260805_141530")
        sig = "MODE=one_step\nSTAGED_PHASE="
        write_pointers(tmp_path, run_dir, sig)
        assert read_pointer(tmp_path) == str(run_dir)
        assert read_last_signature(tmp_path) == sig

    def test_clear_pointers_idempotent_on_empty_dir(self, tmp_path):
        clear_pointers(tmp_path)  # must not raise

    def test_clear_pointers_removes_both_files(self, tmp_path):
        (tmp_path / RUN_DIR_FILE).write_text("x\n")
        (tmp_path / RUN_SIG_FILE).write_text("y")
        clear_pointers(tmp_path)
        assert not (tmp_path / RUN_DIR_FILE).exists()
        assert not (tmp_path / RUN_SIG_FILE).exists()


