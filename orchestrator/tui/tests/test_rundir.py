class TestDiscover:
    def test_no_pointer_file(self, tmp_path):
        assert discover(tmp_path) is None

    def test_empty_pointer(self, tmp_path):
        (tmp_path / RUN_DIR_FILE).write_text("")
        assert discover(tmp_path) is None

    def test_pointer_to_nonexistent_path(self, tmp_path):
        (tmp_path / RUN_DIR_FILE).write_text(
            "artifacts/run_one_step_20260805_141530\n"
        )
        assert discover(tmp_path) is None

    def test_pointer_to_file_not_directory(self, tmp_path):
        target_dir = tmp_path / ARTIFACTS_DIR
        target_dir.mkdir()
        (target_dir / "not_a_dir").write_text("x")
        (tmp_path / RUN_DIR_FILE).write_text("artifacts/not_a_dir\n")
        assert discover(tmp_path) is None

    def test_directory_exists_no_state_json(self, tmp_path):
        run_dir = tmp_path / ARTIFACTS_DIR / "run_one_step_20260805_141530"
        run_dir.mkdir(parents=True)
        (tmp_path / RUN_DIR_FILE).write_text(
            "artifacts/run_one_step_20260805_141530\n"
        )
        assert discover(tmp_path) is None

    def test_state_json_is_a_directory(self, tmp_path):
        run_dir = tmp_path / ARTIFACTS_DIR / "run_one_step_20260805_141530"
        (run_dir / STATE_FILE).mkdir(parents=True)
        (tmp_path / RUN_DIR_FILE).write_text(
            "artifacts/run_one_step_20260805_141530\n"
        )
        assert discover(tmp_path) is None

    @staticmethod
    def _seed_valid_run(tmp_path, *, dir_name="run_one_step_20260805_141530", with_sig=False):
        raw = f"{ARTIFACTS_DIR}/{dir_name}"
        run_dir = tmp_path / ARTIFACTS_DIR / dir_name
        run_dir.mkdir(parents=True)
        (run_dir / STATE_FILE).write_text("{}")
        (tmp_path / RUN_DIR_FILE).write_text(raw + "\n")
        if with_sig:
            (tmp_path / RUN_SIG_FILE).write_text("MODE=one_step")
        return raw, run_dir

    def test_valid_candidate_no_signature_file(self, tmp_path):
        raw, run_dir = self._seed_valid_run(tmp_path)

        candidate = discover(tmp_path)

        assert candidate is not None
        assert candidate.raw_pointer == raw
        assert candidate.run_dir == run_dir
        assert candidate.dir_mode == "one_step"
        assert candidate.dir_ts == "20260805_141530"
        assert candidate.last_sig == ""
        assert isinstance(candidate.state_mtime, float)

    def test_valid_candidate_with_signature_file(self, tmp_path):
        self._seed_valid_run(tmp_path, with_sig=True)

        candidate = discover(tmp_path)

        assert candidate.last_sig == "MODE=one_step"

    def test_unparseable_dir_name_still_returns_candidate(self, tmp_path):
        self._seed_valid_run(tmp_path, dir_name="not_matching_pattern")

        candidate = discover(tmp_path)

        assert candidate is not None
        assert candidate.dir_mode is None
        assert candidate.dir_ts is None

    def test_discover_never_mutates_tree(self, tmp_path):
        self._seed_valid_run(tmp_path)
        before = sorted(
            p.relative_to(tmp_path).as_posix() for p in tmp_path.rglob("*")
        )

        discover(tmp_path)

        after = sorted(
            p.relative_to(tmp_path).as_posix() for p in tmp_path.rglob("*")
        )
        assert before == after


def _make_candidate(*, dir_mode, last_sig):
    return ResumeCandidate(
        raw_pointer="artifacts/run_x_20260805_141530",
        run_dir=Path("artifacts/run_x_20260805_141530"),
        dir_mode=dir_mode,
        dir_ts="20260805_141530",
        last_sig=last_sig,
        state_mtime=0.0,
    )


CURRENT_SIG = "MODE=one_step\nSTAGED_PHASE="
OTHER_SIG = "MODE=one_step\nSTAGED_PHASE=dump_only"

