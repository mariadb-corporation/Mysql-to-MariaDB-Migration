class TestResumeDecision:
    @pytest.mark.parametrize(
        "mode, has_candidate, last_sig, force, expected",
        RESUME_TABLE,
        ids=RESUME_TABLE_IDS,
    )
    def test_table(self, mode, has_candidate, last_sig, force, expected):
        candidate = (
            _make_candidate(dir_mode=mode, last_sig=last_sig)
            if has_candidate
            else None
        )
        decision = resume_decision(
            candidate, mode=mode, current_sig=CURRENT_SIG, force_new_run=force
        )
        assert decision.verdict == expected

    def test_no_candidate_message_empty(self):
        decision = resume_decision(
            None, mode="one_step", current_sig=CURRENT_SIG, force_new_run=False
        )
        assert decision.message == ""

    def test_resume_unconditional_message_empty(self):
        candidate = _make_candidate(dir_mode="binlog", last_sig=OTHER_SIG)
        decision = resume_decision(
            candidate, mode="binlog", current_sig=CURRENT_SIG, force_new_run=False
        )
        assert decision.message == ""

    def test_resume_signature_match_message_empty(self):
        candidate = _make_candidate(dir_mode="one_step", last_sig=CURRENT_SIG)
        decision = resume_decision(
            candidate, mode="one_step", current_sig=CURRENT_SIG, force_new_run=False
        )
        assert decision.message == ""

    @pytest.mark.parametrize(
        "mode, force",
        [
            ("one_step", True),
            ("two_step", False),
            ("one_step", False),
        ],
        ids=["forced", "two_step", "inputs_changed"],
    )
    def test_fresh_messages_non_empty(self, mode, force):
        candidate = _make_candidate(dir_mode=mode, last_sig=OTHER_SIG)
        decision = resume_decision(
            candidate, mode=mode, current_sig=CURRENT_SIG, force_new_run=force
        )
        assert decision.message != ""

    def test_msg_two_step_contains_newline(self):
        assert "\n" in _MSG_TWO_STEP

    def test_can_resume_true_only_for_resume_verdicts(self):
        for verdict in ResumeVerdict:
            decision = ResumeDecision(
                verdict=verdict, candidate=None, message="", mode_mismatch=False
            )
            expected = verdict in (
                ResumeVerdict.RESUME_UNCONDITIONAL,
                ResumeVerdict.RESUME_SIGNATURE_MATCH,
            )
            assert decision.can_resume is expected

    def test_mode_mismatch_true_and_verdict_still_unconditional(self):
        candidate = _make_candidate(dir_mode="one_step", last_sig="")
        decision = resume_decision(
            candidate, mode="binlog", current_sig=CURRENT_SIG, force_new_run=False
        )
        assert decision.mode_mismatch is True
        assert decision.verdict == ResumeVerdict.RESUME_UNCONDITIONAL

    def test_mode_mismatch_false_when_dir_mode_matches(self):
        candidate = _make_candidate(dir_mode="binlog", last_sig="")
        decision = resume_decision(
            candidate, mode="binlog", current_sig=CURRENT_SIG, force_new_run=False
        )
        assert decision.mode_mismatch is False

    def test_mode_mismatch_false_when_dir_mode_none(self):
        candidate = _make_candidate(dir_mode=None, last_sig="")
        decision = resume_decision(
            candidate, mode="binlog", current_sig=CURRENT_SIG, force_new_run=False
        )
        assert decision.mode_mismatch is False

    def test_mode_mismatch_false_when_candidate_none(self):
        decision = resume_decision(
            None, mode="binlog", current_sig=CURRENT_SIG, force_new_run=False
        )
        assert decision.mode_mismatch is False
