class TestRunSignature:
    def test_signature_keys_count_and_order(self):
        assert len(SIGNATURE_KEYS) == 25
        assert SIGNATURE_KEYS == EXPECTED_SIGNATURE_KEYS

    def test_golden_fixture(self):
        fixture_text = (FIXTURES_DIR / "one_step_wizard_v1.sig").read_text()
        fields = json.loads((FIXTURES_DIR / "one_step_wizard_v1.json").read_text())
        fields = {k: v for k, v in fields.items() if k != "_generated_by"}
        mode = fields.pop("MODE")
        draft = ConfigDraft(mode=mode, **fields)

        result = run_signature(draft)

        assert result == fixture_text
        assert result.count("\n") == 24

    def test_signature_survives_config_load_round_trip(self):
        """A config loaded via configio.yaml_to_draft must still produce a
        wizard-parity signature -- this is the regression test for review
        findings F2/F3: yaml_to_draft's fallback defaults for
        INSTALL_TARGET_MARIADB and SRC_DBS_INPUT previously produced "" for
        any config missing those keys (which config/migration.yaml.example
        does), breaking signature parity for every non-binlog/replace_slave
        mode. The fixture signature was generated by sourcing and invoking
        the real mariadb-migrator run_signature() bash function directly
        with config/migration.yaml.example's exact field values.
        """
        from orchestrator.tui.configio import yaml_to_draft

        example_path = (
            Path(__file__).parent.parent.parent.parent
            / "config"
            / "migration.yaml.example"
        )
        draft = yaml_to_draft(example_path.read_text())

        fixture_text = (
            FIXTURES_DIR / "example_config_wizard_v1.sig"
        ).read_text()
        assert run_signature(draft) == fixture_text

    def test_default_install_target_mariadb_parity(self):
        draft = ConfigDraft(mode="one_step")
        lines = run_signature(draft).split("\n")
        assert "INSTALL_TARGET_MARIADB=0" in lines
        assert "TARGET_INSTALL_OS=" in lines
        assert "TARGET_MARIADB_VERSION=" in lines

    def test_no_password_in_signature(self):
        sentinel = "SENTINEL_SECRET_VALUE"
        password_fields = [
            f.name
            for f in dataclasses.fields(ConfigDraft)
            if "PASS" in f.name or f.name == "APP_USER_DEFAULT_PASSWORD"
        ]
        assert password_fields, "expected at least one password-like field"
        kwargs = {name: sentinel for name in password_fields}
        draft = ConfigDraft(mode="one_step", **kwargs)

        sig = run_signature(draft)

        assert sentinel not in sig

    def test_src_dbs_input_raw_not_split(self):
        draft = ConfigDraft(
            mode="one_step",
            SRC_DB="db1",
            SRC_DBS="db2",
            SRC_DBS_INPUT="db1, db2",
        )
        lines = run_signature(draft).split("\n")
        assert "SRC_DBS_INPUT=db1, db2" in lines

    @pytest.mark.parametrize(
        "staged_phase_field, expected_line",
        [
            ("dump_only", "STAGED_PHASE=dump_only"),
            ("", "STAGED_PHASE="),
        ],
        ids=["set", "empty"],
    )
    def test_staged_phase_resolution(self, staged_phase_field, expected_line):
        draft = ConfigDraft(mode="staged", STAGED_PHASE=staged_phase_field)
        lines = run_signature(draft).split("\n")
        assert expected_line in lines

    def test_empty_field_renders_bare_key(self):
        draft = ConfigDraft(mode="one_step")
        lines = run_signature(draft).split("\n")
        assert "REPL_USER=" in lines

    def test_staged_dump_dir_is_real_configdraft_field(self):
        assert "STAGED_DUMP_DIR" in {f.name for f in dataclasses.fields(ConfigDraft)}


